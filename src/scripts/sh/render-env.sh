#!/bin/bash

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
PROJECT_NAME="$(basename "${PROJECT_ROOT}")"
DEFAULT_SERVICE_NAME=""
DEFAULT_REQUIRED_KEYS=""

case "${PROJECT_NAME}" in
    heros-companion)
        DEFAULT_SERVICE_NAME="heros-companion"
        DEFAULT_REQUIRED_KEYS="NODE_ENV,NODE_VERSION,DB_PG_INTERNAL_HOSTNAME,DB_PG_PORT,DB_PG_DATABASE,DB_PG_USER,DB_PG_PASSWORD,DB_PG_POOL_MAX,IAM_URL,IAM_CLIENT_SECRET,SESSION_SECRET,GITHUB_TOKEN"
        ;;
    FlashCards)
        DEFAULT_SERVICE_NAME="FlashCards"
        DEFAULT_REQUIRED_KEYS="NODE_ENV,SESSION_SECRET,DB_PG_INTERNAL_HOSTNAME,DB_PG_PORT,DB_PG_DATABASE,DB_PG_USER,DB_PG_PASSWORD,IAM_URL,IAM_CLIENT_SECRET,GITHUB_TOKEN"
        ;;
    iam-service)
        DEFAULT_SERVICE_NAME="iam-service"
        DEFAULT_REQUIRED_KEYS="NODE_ENV,DB_PG_INTERNAL_HOSTNAME,DB_PG_PORT,DB_PG_DATABASE,DB_PG_USER,DB_PG_PASSWORD,IAM_CLIENT_SECRET_FLASHCARDS,IAM_CLIENT_SECRET_HEROS_COMPANION"
        ;;
    CSE340)
        DEFAULT_SERVICE_NAME="CSE340"
        DEFAULT_REQUIRED_KEYS="DB_URL"
        ;;
    wurm-tools-web)
        DEFAULT_SERVICE_NAME="wurm-tools-web"
        DEFAULT_REQUIRED_KEYS="NODE_ENV,NODE_VERSION,SESSION_SECRET,GITHUB_TOKEN"
        ;;
    wurm-tools)
        DEFAULT_SERVICE_NAME="wurm-tools"
        ;;
esac

RENDER_ENV_FILE="${PROJECT_ROOT}/.env" \
RENDER_SERVICE_NAME="${RENDER_SERVICE_NAME-${DEFAULT_SERVICE_NAME}}" \
RENDER_REQUIRED_KEYS="${RENDER_REQUIRED_KEYS-${DEFAULT_REQUIRED_KEYS}}" \
node "${PROJECT_ROOT}/src/scripts/js/modules/tools/renderEnv.mjs" "$@"
